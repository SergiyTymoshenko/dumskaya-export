# ---------- запись ----------
def write(page, keep_from=None):
    path = page['path']
    old = RU.get(path)
    f = old[0] if old else os.path.join(PAGES, 'ru', path.strip('/') + '.json')
    sections = []
    for s in page['sections']:
        if s == '__GALLERIES__':
            for os_ in old[1]['sections']:
                if str(os_.get('id') or '').startswith('city-'): continue   # свои секции прошлого запуска
                if any(b['type'] == 'gallery' and len(b['images']) > 1 for b in os_['blocks']):
                    sections.append(copy.deepcopy(os_))
            continue
        sections.append(s)
    for i, s in enumerate(sections):
        if not s.get('id'): s['id'] = f'city-{path.strip("/").replace("/", "-")}-{i}'
    out = {
        'path': path, 'lang': 'ru', 'type': page['type'], 'group': None,
        'title': page['title'], 'description': page['description'], 'h1': page['h1'],
        'og_image': page['og'],
        'alternates': old[1]['alternates'] if old else page.get('alternates', {'ru': path}),
        'sections': sections,
    }
    if page.get('phone'):   # посадочная страница региона: телефон в шапке и под заголовком
        out = {**{k: v for k, v in out.items() if k != 'sections'}, 'phone': page['phone'],
               **({'phone_plain': True} if page.get('phone_plain') else {}), 'sections': sections}
    json.dump(out, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    assert len(page['title']) <= 60, (path, len(page['title']))
    assert len(page['description']) <= 155, (path, len(page['description']))
    print(('обновлена ' if old else 'создана   ') + path)

