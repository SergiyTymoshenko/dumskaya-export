# ---------- кирпичики ----------
def H(level, text): return {'type': 'heading', 'level': level, 'text': text}
def P(*html): return {'type': 'text', 'parts': [{'t': 'p', 'html': h} for h in html]}
def UL(*items): return {'type': 'text', 'parts': [{'t': 'ul', 'items': list(items)}]}
def OL(*items): return {'type': 'text', 'parts': [{'t': 'ol', 'items': list(items)}]}
def BTN(*items): return {'type': 'buttons', 'items': [{'text': t, 'href': h} for t, h in items]}
def FAQ(*qa): return {'type': 'faq', 'items': [{'q': q, 'a': a} for q, a in qa]}
def FACTS(title, *rows): return {'type': 'facts', 'title': title, 'rows': [list(r) for r in rows]}
FORM = {'type': 'form'}

def gallery_of(path):
    _, p = RU[path]
    for s in p['sections']:
        for b in s['blocks']:
            if b['type'] == 'gallery': return b['images']
    return []

def GAL(spec):
    """spec: [(путь проекта, [индексы фото]), ...] — фото берутся из галерей проектов вместе с подписями."""
    imgs = []
    for path, idx in spec:
        g = gallery_of(path)
        imgs += [copy.deepcopy(g[i]) for i in idx if i < len(g)]
    return {'type': 'gallery', 'images': imgs}

def CARDS(paths):
    items = []
    for path in paths:
        pr = PROJECTS.get(path)
        if pr:
            items.append({'title': pr['title']['ru'], 'href': path, 'image': {'id': pr['cover'], 'alt': pr['title']['ru']}})
        else:
            _, p = RU[path]
            items.append({'title': p['h1'], 'href': path, 'image': {'id': p.get('og_image') or gallery_of(path)[0]['id'], 'alt': p['h1']}})
    return {'type': 'cards', 'items': items}

